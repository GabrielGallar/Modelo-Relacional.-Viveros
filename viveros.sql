create table public.vivero (
	id_vivero int4 generated by default as identity not null,
	latitud numeric(9, 6) not null,
	longitud numeric(9, 6) not null,
	constraint latitud_check check (latitud >= -90 and latitud <= 90),
	constraint longitud_check check (longitud >= -180 and longitud <= 180),
	constraint vivero_pk primary key (id_vivero)
);

create table public.producto (
	id_producto int4 generated by default as identity not null,
	tipo varchar(100) null,
	constraint producto_pk primary key (id_producto)
);

create table public.cliente (
	id_cliente int4 generated by default as identity not null,
	nombre varchar(100) null,
	apellido varchar(100) null,
	fecha_suscripcion date null,
	constraint cliente_pk primary key (id_cliente)
);

create table public.empleado (
	id_empleado int4 generated by default as identity not null,
	nombre varchar(100) null,
	apellido1 varchar(100) null,
	apellido2 varchar(100) null,
	constraint empleado_pk primary key (id_empleado)
);

create table public.tarea (
	id_tarea int4 generated by default as identity not null,
	tipo varchar(100) null,
	constraint tarea_pk primary key (id_tarea)
);

create table public.zona (
	id_zona int4 generated by default as identity not null,
	vivero int4 not null,
	tipo varchar(100) null,
	latitud numeric(9, 6) not null,
	longitud numeric(9, 6) not null,
	constraint latitud_check check (latitud >= -90 and latitud <= 90),
	constraint longitud_check_1 check (longitud >= -180 and longitud <= 180),
	constraint zona_pk primary key (id_zona),
	constraint zona_vivero_fk foreign key (vivero) references public.vivero(id_vivero) on delete cascade
);

create table public.producto_en_zona (
	producto int4 not null,
	zona int4 not null,
	cantidad int4 null,
	constraint producto_en_zona_check check (cantidad >= 0),
	constraint producto_en_zona_pk primary key (producto, zona),
	constraint producto_en_zona_producto_fk foreign key (producto) references public.producto(id_producto) on delete cascade,
	constraint producto_en_zona_zona_fk foreign key (zona) references public.zona(id_zona) on delete cascade
);

create table public.pedido (
	id_pedido int4 generated by default as identity not null,
	responsable int4 not null,
	cliente int4 not null,
	fecha date null,
	tipo varchar(100) null,
	constraint pedido_pk primary key (id_pedido),
	constraint pedido_cliente_fk foreign key (cliente) references public.cliente(id_cliente),
	constraint pedido_empleado_fk foreign key (responsable) references public.empleado(id_empleado)
);

create table public.bonificacion (
	cliente int4 not null,
	mes date not null,
	volumen_compra numeric(10, 2) not null,
	importe numeric(10, 2) not null,
	constraint bonificacion_pk primary key (cliente, mes),
	constraint importe_check check (importe >= 0),
	constraint volumen_compra_check check (volumen_compra >= 0),
	constraint bonificacion_cliente_fk foreign key (cliente) references public.cliente(id_cliente)
);

create table public.cargo (
	id_cargo int4 generated by default as identity not null,
	empleado int4 not null,
	tarea int4 not null,
	zona int4 not null,
	fecha_inicio date not null,
	fecha_fin date null,
	constraint cargo_pk primary key (id_cargo),
	constraint fecha_fin_check check (fecha_fin is null or fecha_fin >= fecha_inicio),
	constraint cargo_empleado_fk foreign key (empleado) references public.empleado(id_empleado),
	constraint cargo_tarea_fk foreign key (tarea) references public.tarea(id_tarea),
	constraint cargo_zona_fk foreign key (zona) references public.zona(id_zona)
);

